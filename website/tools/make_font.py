"""Builds the website's copy of the game's 3x5 font from art/ui/font.png.

Writes website/assets/fonts/luxel35.woff (+ .ttf) and website/src/js/glyphs.js (the same bitmaps for canvas).
One font pixel = 125 units, 1000 units per em: at font-size 8n px every font pixel is exactly n css px.
Run once (outputs are checked in):
  uv run --no-project --with fonttools --with pillow python website/tools/make_font.py
"""
from pathlib import Path
import json

from PIL import Image
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

ROOT = Path(__file__).resolve().parents[2]
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!-:x/.+="  # PixelFont.CHARS
PX = 125
ADV = 4  # 3 px glyph + 1 px gap, as in the game

# Glyphs the game font lacks (web only), drawn in the same 3x5 grid. "%" is the settings menu's.
EXTRA = {
    "?": ["###", "..#", ".##", "...", ".#."],
    ",": ["...", "...", "...", ".#.", "#.."],
    "'": [".#.", ".#.", "...", "...", "..."],
    '"': ["#.#", "#.#", "...", "...", "..."],
    "(": ["..#", ".#.", ".#.", ".#.", "..#"],
    ")": ["#..", ".#.", ".#.", ".#.", "#.."],
    "%": ["#.#", "..#", ".#.", "#..", "#.#"],
    "&": [".#.", "#.#", ".#.", "#.#", ".##"],
    "#": ["#.#", "###", "#.#", "###", "#.#"],
    ";": ["...", ".#.", "...", ".#.", "#.."],
    "_": ["...", "...", "...", "...", "###"],
    "@": ["###", "#.#", "#.#", "#..", "###"],
    "*": ["#.#", ".#.", "#.#", "...", "..."],
    "<": ["..#", ".#.", "#..", ".#.", "..#"],
    ">": ["#..", ".#.", "..#", ".#.", "#.."],
    "[": ["##.", "#..", "#..", "#..", "##."],
    "]": [".##", "..#", "..#", "..#", ".##"],
    "|": [".#.", ".#.", ".#.", ".#.", ".#."],
    "·": ["...", "...", ".#.", "...", "..."],
    "▶": ["#..", "##.", "###", "##.", "#.."],
    "◀": ["..#", ".##", "###", ".##", "..#"],
    "©": ["###", "#..", "#..", "#..", "###"],
    "$": [".##", "##.", ".#.", ".##", "##."],
    "^": [".#.", "#.#", "...", "...", "..."],
}
# Characters drawn with another glyph.
ALIAS = {"–": "-", "—": "-", "’": "'", "‘": "'", "“": '"', "”": '"', "…": ".",
         "→": "▶", "←": "◀", "×": "x", "•": "·", "é": "E", "É": "E"}


def glyph_rows() -> dict:
    img = Image.open(ROOT / "art/ui/font.png").convert("RGBA")
    rows = {}
    for i, ch in enumerate(CHARS):
        rows[ch] = ["".join("#" if img.getpixel((i * 3 + x, y))[3] > 127 else "." for x in range(3)) for y in range(5)]
    rows.update(EXTRA)
    return rows


def draw(rows: list) -> object:
    pen = TTGlyphPen(None)
    for y, row in enumerate(rows):
        x = 0
        while x < 3:
            if row[x] != "#":
                x += 1
                continue
            x0 = x
            while x < 3 and row[x] == "#":
                x += 1
            top, bottom = (5 - y) * PX, (4 - y) * PX
            pen.moveTo((x0 * PX, bottom))
            pen.lineTo((x0 * PX, top))
            pen.lineTo((x * PX, top))
            pen.lineTo((x * PX, bottom))
            pen.closePath()
    return pen.glyph()


def name_of(ch: str) -> str:
    return "u%04X" % ord(ch)


def main() -> None:
    rows = glyph_rows()
    order = [".notdef", "space"] + [name_of(c) for c in rows]
    glyphs = {".notdef": draw(["###", "#.#", "#.#", "#.#", "###"]), "space": TTGlyphPen(None).glyph()}
    cmap = {32: "space", 0xA0: "space"}
    for ch, r in rows.items():
        glyphs[name_of(ch)] = draw(r)
        cmap[ord(ch)] = name_of(ch)
        if ch.isalpha() and ch.isupper():
            cmap[ord(ch.lower())] = name_of(ch)
    cmap[ord("x")] = name_of("X")  # body text: x is a letter; the game's small x answers to the times sign
    cmap[0xD7] = name_of("x")
    for src, dst in ALIAS.items():
        if src not in cmap and ord(src) not in cmap:
            cmap[ord(src)] = name_of(dst)
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (ADV * PX, 0) for g in order})
    fb.setupHorizontalHeader(ascent=7 * PX, descent=-2 * PX)
    fb.setupNameTable({"familyName": "Luxel 3x5", "styleName": "Regular"})
    fb.setupOS2(version=4, sTypoAscender=7 * PX, sTypoDescender=-2 * PX, sTypoLineGap=0, usWinAscent=7 * PX,
                usWinDescent=2 * PX, sxHeight=5 * PX, sCapHeight=5 * PX, fsSelection=0x40 | 0x80)
    fb.setupPost()
    out = ROOT / "website/assets/fonts"
    out.mkdir(parents=True, exist_ok=True)
    fb.save(str(out / "luxel35.ttf"))
    fb.font.flavor = "woff"
    fb.save(str(out / "luxel35.woff"))
    bits = {ch: [int(r.replace("#", "1").replace(".", "0"), 2) for r in rws] for ch, rws in rows.items()}
    alias = {k: v for k, v in ALIAS.items()}
    js = ("// Generated by website/tools/make_font.py from art/ui/font.png: 3x5 glyphs, 5 rows of 3 bits (MSB = left).\n"
          "window.LUX_GLYPHS = " + json.dumps(bits, ensure_ascii=True, separators=(",", ":")) + ";\n"
          "window.LUX_ALIAS = " + json.dumps(alias, ensure_ascii=True, separators=(",", ":")) + ";\n")
    (ROOT / "website/src/js/00_glyphs.js").write_text(js)
    print("font:", len(rows), "glyphs", (out / "luxel35.woff").stat().st_size, "bytes woff")


if __name__ == "__main__":
    main()
