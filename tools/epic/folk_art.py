HEX = {
    "void": "#0d0b1e", "night": "#211a3b", "dusk": "#3d2c5c", "plum": "#6a3d6f",
    "wine": "#a0466a", "coral": "#e2725b", "apricot": "#f5a96a", "gold": "#ffd98c",
    "cream": "#fff4dc", "pine": "#1d3d4c", "teal": "#2b6b68", "jade": "#4c9e78",
    "lime": "#a3cf7d", "deep": "#263873", "blue": "#3e6db0", "sky": "#78a9da",
    "ice": "#c7e5ef", "mauve": "#8a6e91", "stone": "#c2a7ae", "rose": "#ec9fa8",
}

def _rgba(name: str) -> tuple[int, int, int, int]:
    h = HEX[name].lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)

PAL = {k: _rgba(k) for k in HEX}
TRANS = (0, 0, 0, 0)
VALID_RGBA = set(PAL.values()) | {TRANS}

CMAP = {
    ".": TRANS,
    "v": PAL["void"], "n": PAL["night"], "d": PAL["dusk"], "p": PAL["plum"],
    "w": PAL["wine"], "r": PAL["coral"], "a": PAL["apricot"], "g": PAL["gold"],
    "c": PAL["cream"], "P": PAL["pine"], "t": PAL["teal"], "j": PAL["jade"],
    "l": PAL["lime"], "D": PAL["deep"], "b": PAL["blue"], "s": PAL["sky"],
    "i": PAL["ice"], "m": PAL["mauve"], "S": PAL["stone"], "R": PAL["rose"],
}


def verify_palette(img: Image.Image, label: str) -> None:
    px = img.load()
    w, h = img.size
    for y in range(h):
        for x in range(w):
            c = px[x, y]
            if c not in VALID_RGBA:
                raise ValueError(f"{label}: bad pixel at ({x},{y}): {c}")


def draw_grid(rows: list[str], w: int, h: int, override: dict[str, tuple[int, int, int, int]] | None = None) -> Image.Image:
    img = Image.new("RGBA", (w, h), TRANS)
    px = img.load()
    lut = dict(CMAP)
    if override:
        lut.update(override)
    for y, row in enumerate(rows[:h]):
        for x, ch in enumerate(row[:w]):
            col = lut.get(ch, TRANS)
            if col != TRANS:
                px[x, y] = col
    return img


def shift_img(img: Image.Image, dx: int, dy: int) -> Image.Image:
    out = Image.new("RGBA", img.size, TRANS)
    out.paste(img, (dx, dy))
    return out


def add_pixels(img: Image.Image, pts: list[tuple[int, int, str]]) -> Image.Image:
    out = img.copy()
    px = out.load()
    w, h = out.size
    for x, y, ck in pts:
        if 0 <= x < w and 0 <= y < h:
            px[x, y] = PAL[ck] if ck in PAL else CMAP.get(ck, TRANS)
    return out


