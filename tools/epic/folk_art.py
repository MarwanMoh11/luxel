def build_folk_sheets() -> None:
    FOLK_DIR.mkdir(parents=True, exist_ok=True)
    for fid, fname, base_rows, talk_pts, happy_pts in FOLK_SPECS:
        base = draw_grid(base_rows, 16, 20)
        idle0 = base
        idle1 = shift_img(base, 0, -1)
        talk0 = add_pixels(base, talk_pts)
        talk1 = add_pixels(shift_img(base, 0, -1), talk_pts)
        happy0 = add_pixels(shift_img(base, 0, -1), happy_pts)
        happy1 = add_pixels(shift_img(base, 0, -2), happy_pts)

        # Layout: 2 cols x 3 rows of 16x20 -> 32x60 sheet
        sheet = Image.new("RGBA", (32, 60), TRANS)
        frames = [
            (0, 0, idle0), (16, 0, idle1),
            (0, 20, talk0), (16, 20, talk1),
            (0, 40, happy0), (16, 40, happy1),
        ]
        for x, y, fr in frames:
            sheet.paste(fr, (x, y))
        verify_palette(sheet, fid)

        png_path = FOLK_DIR / f"{fid}.png"
        json_path = FOLK_DIR / f"{fid}.json"
        sheet.save(png_path)
        meta = {
            "id": fid,
            "name": fname,
            "sheet": f"{fid}.png",
            "frame": [16, 20],
            "anchor": [8, 18],
            "animations": {
                "idle": {
                    "loop": True,
                    "anchor": [8, 18],
                    "dirs": {
                        "front": {"rects": [[0, 0, 16, 20], [16, 0, 16, 20]], "ms": [480, 480]},
                        "side": {"rects": [[0, 0, 16, 20], [16, 0, 16, 20]], "ms": [480, 480]},
                    },
                },
                "talk": {
                    "loop": True,
                    "anchor": [8, 18],
                    "dirs": {
                        "front": {"rects": [[0, 20, 16, 20], [16, 20, 16, 20]], "ms": [180, 180]},
                        "side": {"rects": [[0, 20, 16, 20], [16, 20, 16, 20]], "ms": [180, 180]},
                    },
                },
                "happy": {
                    "loop": True,
                    "anchor": [8, 18],
                    "dirs": {
                        "front": {"rects": [[0, 40, 16, 20], [16, 40, 16, 20]], "ms": [220, 220]},
                        "side": {"rects": [[0, 40, 16, 20], [16, 40, 16, 20]], "ms": [220, 220]},
                    },
                },
            },
        }
        json_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(FOLK_SPECS)} lamp-folk sheets into {FOLK_DIR} (palette OK)")


