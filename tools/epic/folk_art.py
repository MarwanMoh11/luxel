def build_bubble_icons() -> None:
    UI_DIR.mkdir(parents=True, exist_ok=True)
    cols = 11
    rows = (len(BUBBLE_ICONS) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * 9, rows * 9), TRANS)
    icons_meta: dict[str, list[int]] = {}
    props_meta: dict[str, dict] = {}
    seen: set[str] = set()

    for idx, (iid, grid_rows) in enumerate(BUBBLE_ICONS):
        if iid in seen:
            raise ValueError(f"Duplicate bubble icon id: {iid}")
        seen.add(iid)
        icon = draw_grid(grid_rows, 9, 9)
        cx = (idx % cols) * 9
        cy = (idx // cols) * 9
        sheet.paste(icon, (cx, cy))
        icons_meta[iid] = [cx, cy, 9, 9]
        props_meta[iid] = {
            "rects": [[cx, cy, 9, 9]],
            "ms": [200],
            "loop": False,
            "anchor": [4, 4],
        }

    verify_palette(sheet, "bubble_icons")
    png_path = UI_DIR / "bubble_icons.png"
    json_path = UI_DIR / "bubble_icons.json"
    sheet.save(png_path)
    meta = {
        "sheet": "bubble_icons.png",
        "icon_size": [9, 9],
        "grid": [cols, rows],
        "count": len(BUBBLE_ICONS),
        "anchor": [4, 4],
        "icons": icons_meta,
        "props": props_meta,
    }
    json_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {png_path} ({sheet.size[0]}x{sheet.size[1]}) and {json_path} ({len(BUBBLE_ICONS)} icons, palette OK)")


def main() -> None:
    build_folk_sheets()
    build_bubble_icons()


if __name__ == "__main__":
    main()
